// Config files and profiles (SPEC §4.4)

#[derive(Debug, Deserialize, Docuconf)]
#[docuconf(prefix = "APP_")]
#[allow(dead_code)]
struct Svc {
    /// Deployment profile: production or staging.
    #[docuconf(default = "production")]
    profile: String,
    /// Warehouse API base URL.
    #[docuconf(schemes("https"))]
    warehouse_api: Url,
    /// Number of background workers.
    #[docuconf(default = 4, min = 1)]
    workers: u32,
    /// Payment provider API key.
    api_key: Secret<String>,
}

const APP_TOML: &str = r#"
[default]
workers = 8

[production]
warehouse_api = "https://warehouse.internal"

[staging]
warehouse_api = "https://warehouse.staging.internal"
workers = 2
"#;

fn svc_loader() -> docuconf::Loader<Svc> {
    docuconf::Loader::new()
        .figment(Figment::from(Toml::string(APP_TOML).nested()))
        .profiles("APP_PROFILE", "production")
        .termination_log(false)
}

#[test]
fn profiles_are_exported() {
    let out = svc_loader().export(&Meta::new("svc")).unwrap();
    assert!(
        out.contains(
            "\tprofiles: {\n\t\tselector: \"APP_PROFILE\"\n\t\tdefault:  \"production\"\n\t\tdefaults: {\n\t\t\tproduction: {\n\t\t\t\tAPP_WAREHOUSE_API: \"https://warehouse.internal\"\n\t\t\t}\n\t\t\tstaging: {\n\t\t\t\tAPP_WAREHOUSE_API: \"https://warehouse.staging.internal\"\n\t\t\t\tAPP_WORKERS:       2\n\t\t\t}\n\t\t}\n\t}\n"
        ),
        "{out}"
    );
    // The base file's value is the default.
    assert!(
        out.contains("APP_WORKERS: {\n\t\t\ttype:        \"int\"\n\t\t\tdescription: \"Number of background workers\"\n\t\t\tdefault:     8\n"),
        "{out}"
    );
    if let Some(res) = cue_vet(&out) {
        res.unwrap_or_else(|e| panic!("cue vet failed:\n{e}\n{out}"));
    }
}

#[test]
fn profiles_select_values_and_env_wins() {
    let base = [("APP_API_KEY", "k")];
    let s = svc_loader().env(base).load().unwrap();
    assert_eq!(s.warehouse_api.as_str(), "https://warehouse.internal/");
    assert_eq!(s.workers, 8);

    let s = svc_loader()
        .env([("APP_API_KEY", "k"), ("APP_PROFILE", "staging")])
        .load()
        .unwrap();
    assert_eq!(s.profile, "staging");
    assert_eq!(
        s.warehouse_api.as_str(),
        "https://warehouse.staging.internal/"
    );
    assert_eq!(s.workers, 2);

    let s = svc_loader()
        .env([
            ("APP_API_KEY", "k"),
            ("APP_PROFILE", "staging"),
            ("APP_WORKERS", "3"),
        ])
        .load()
        .unwrap();
    assert_eq!(
        s.workers, 3,
        "the platform's variables override file values"
    );

    // A profile with no file makes the platform responsible.
    let err = svc_loader()
        .env([("APP_API_KEY", "k"), ("APP_PROFILE", "dev")])
        .load()
        .unwrap_err();
    assert_eq!(
        err.violations()
            .iter()
            .map(|v| (v.input.as_str(), v.code))
            .collect::<Vec<_>>(),
        [("APP_WAREHOUSE_API", Code::MissingRequired)]
    );
}

#[test]
fn bad_file_values_fail_export_and_load() {
    let toml = "[default]\nworkers = 0\n[production]\nwarehouse_api = \"http://plain\"\n";
    let loader = || {
        docuconf::Loader::<Svc>::new()
            .figment(Figment::from(Toml::string(toml).nested()))
            .profiles("APP_PROFILE", "production")
            .termination_log(false)
    };
    let err = loader().export(&Meta::new("svc")).unwrap_err();
    let all = err.problems.join("\n");
    assert!(
        all.contains(
            "APP_WORKERS (Svc.workers): config file value (profile default) 0 is below min 1"
        ),
        "{all}"
    );
    assert!(all.contains("APP_WAREHOUSE_API (Svc.warehouse_api): config file value (profile production) \"http://plain\" has scheme http"), "{all}");

    let err = loader().env([("APP_API_KEY", "k")]).load().unwrap_err();
    let mut codes: Vec<_> = err
        .violations()
        .iter()
        .map(|v| (v.input.as_str(), v.code))
        .collect();
    codes.sort();
    assert_eq!(
        codes,
        [
            ("APP_WAREHOUSE_API", Code::InvalidScheme),
            ("APP_WORKERS", Code::OutOfRange)
        ]
    );
}

#[test]
fn secrets_must_not_be_in_config_files() {
    let toml = "[default]\napi_key = \"sk_live_123\"\nwarehouse_api = \"https://w\"\n";
    let err = docuconf::Loader::<Svc>::new()
        .figment(Figment::from(Toml::string(toml).nested()))
        .profiles("APP_PROFILE", "production")
        .export(&Meta::new("svc"))
        .unwrap_err();
    let all = err.problems.join("\n");
    assert!(
        all.contains("APP_API_KEY (Svc.api_key): a secret must not have a value in a config file"),
        "{all}"
    );
    assert!(!all.contains("sk_live_123"));
}

#[test]
fn profiles_need_a_selector() {
    let err = docuconf::Loader::<Svc>::new()
        .figment(Figment::from(Toml::string(APP_TOML).nested()))
        .export(&Meta::new("svc"))
        .unwrap_err();
    assert!(err.to_string().contains("call Loader::profiles"), "{err}");

    let err = docuconf::Loader::<Svc>::new()
        .figment(Figment::from(Toml::string(APP_TOML).nested()))
        .profiles("PROFILE", "production")
        .export(&Meta::new("svc"))
        .unwrap_err();
    assert!(
        err.to_string()
            .contains("profile selector PROFILE must be a declared variable"),
        "{err}"
    );
}

#[test]
fn global_values_override_every_profile() {
    let toml = "[global]\nworkers = 6\n[staging]\nworkers = 2\nwarehouse_api = \"https://s\"\n";
    let loader = || {
        docuconf::Loader::<Svc>::new()
            .figment(Figment::from(Toml::string(toml).nested()))
            .profiles("APP_PROFILE", "production")
            .termination_log(false)
    };
    let out = loader().export(&Meta::new("svc")).unwrap();
    assert!(out.contains("default:     6"), "{out}");
    assert!(!out.contains("APP_WORKERS:       2"), "{out}");
    let s = loader()
        .env([("APP_API_KEY", "k"), ("APP_PROFILE", "staging")])
        .load()
        .unwrap();
    assert_eq!(s.workers, 6, "as figment does, and as the contract says");
}
