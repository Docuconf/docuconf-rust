const GOLDEN: &str = "tests/golden/gateway.cue";

#[test]
fn export_matches_golden() {
    let out = docuconf::export::<Gateway>(&Meta::new("gateway")).unwrap();
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(GOLDEN);
    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &out).unwrap();
    }
    let want = std::fs::read_to_string(&path).unwrap();
    assert_eq!(
        want, out,
        "export changed; run UPDATE_GOLDEN=1 cargo test --test export to accept"
    );
    let again = docuconf::export::<Gateway>(&Meta::new("gateway")).unwrap();
    assert_eq!(out, again, "export must be deterministic");
}

#[test]
fn export_header_and_metadata() {
    let out = docuconf::export::<Gateway>(&Meta::new("gateway-api").app_version("1.2.3")).unwrap();
    assert!(out.starts_with(
        "// Code generated by docuconf. DO NOT EDIT.\npackage gateway_api\n\nimport \"docuconf.dev/contract\"\n\ncontract.#Contract & {\n"
    ));
    assert!(out.contains("appVersion: \"1.2.3\""));
    assert!(out.contains("language: \"rust\""));
    let err = docuconf::export::<Gateway>(&Meta::new("Gateway")).unwrap_err();
    assert!(err.to_string().contains("DNS label"), "{err}");
}

