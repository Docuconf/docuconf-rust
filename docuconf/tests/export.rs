#[test]
fn declaration_errors() {
    #[derive(Debug, Deserialize, Docuconf)]
    #[allow(dead_code)]
    struct Bad {
        /// Lower-case names are not environment variable names.
        #[docuconf(env = "lower")]
        lower: String,
        /// A required variable cannot have a default.
        #[docuconf(required, default = 1)]
        both: i32,
        /// Defaults must satisfy their own constraints.
        #[docuconf(default = 0, min = 1)]
        port: u16,
        /// Patterns must be RE2.
        #[docuconf(pattern = "(?=x)")]
        look: String,
        /// min does not apply to strings.
        #[docuconf(min = 1)]
        str_min: String,
        /// Secrets have no defaults.
        #[docuconf(default = "x")]
        token: Secret<String>,
        no_docs: String,
        /// Durations need humantime_serde.
        #[docuconf(default = "5s")]
        timeout: Duration,
        /// A file input under a reserved directory.
        #[docuconf(path = "/etc/ca.pem")]
        ca: docuconf::CaBundle,
        /// Watching is not implemented.
        #[docuconf(path = "/etc/app/notes/notes.txt", reload = "watch")]
        notes: docuconf::TextFile,
        /// The password of a keystore must be a secret.
        #[docuconf(path = "/etc/app/ks/ks.p12", password_var = "LOWER_NOT_SECRET")]
        ks: docuconf::Keystore,
        /// Not secret, so not a keystore password.
        lower_not_secret: String,
    }
    let err = docuconf::check_declaration::<Bad>().unwrap_err();
    let all = err.problems.join("\n");
    for want in [
        "lower (Bad.lower): variable name must match",
        "BOTH (Bad.both): a required variable must not have a default",
        "PORT (Bad.port): default 0 is below min 1",
        "LOOK (Bad.look): pattern \"(?=x)\" is not valid RE2",
        "STR_MIN (Bad.str_min): attribute `min` does not apply to a string variable",
        "TOKEN (Bad.token): a secret variable must not have a default",
        "NO_DOCS (Bad.no_docs): needs a description",
        "TIMEOUT (Bad.timeout): a Duration field needs #[serde(with = \"docuconf::humantime_serde\")]",
        "file input ca (Bad.ca): would be mounted at /etc",
        "file input notes (Bad.notes): reload = \"watch\" is not implemented",
        "file input ks (Bad.ks): password_var LOWER_NOT_SECRET must be a secret variable",
    ] {
        assert!(all.contains(want), "missing {want:?} in\n{all}");
    }

    // Loading reports the declaration error, not violations.
    let e = docuconf::Loader::<Bad>::new()
        .env(Vec::<(String, String)>::new())
        .load()
        .unwrap_err();
    assert!(matches!(e, Error::Declaration(_)));
}

#[test]
fn mount_collisions_and_path_env_rules() {
    #[derive(Debug, Deserialize, Docuconf)]
    #[allow(dead_code)]
    struct Bad {
        /// First file in a shared directory.
        #[docuconf(path = "/etc/app/shared/a.txt", path_env = "A_FILE")]
        a: docuconf::TextFile,
        /// Second file in a shared directory.
        #[docuconf(path = "/etc/app/shared/b.txt", path_env = "A_FILE")]
        b: docuconf::TextFile,
        /// A path that is not normalised.
        #[docuconf(path = "/etc/app/../x.txt")]
        c: docuconf::TextFile,
        /// Also the name of a variable.
        a_file: Option<String>,
    }
    let err = docuconf::check_declaration::<Bad>().unwrap_err();
    let all = err.problems.join("\n");
    for want in [
        "file input b (Bad.b): shares mount directory /etc/app/shared with file input a",
        "path_env A_FILE must not also be a declared variable",
        "path_env A_FILE is also used by file input a",
        "file input c (Bad.c): path \"/etc/app/../x.txt\" must be absolute and normalised",
    ] {
        assert!(all.contains(want), "missing {want:?} in\n{all}");
    }
}

