#[test]
fn export_passes_cue_vet() {
    let out = docuconf::export::<Gateway>(&Meta::new("gateway").app_version("1.2.3")).unwrap();
    let Some(res) = cue_vet(&out) else { return };
    res.unwrap_or_else(|e| panic!("cue vet failed:\n{e}\n{out}"));

    // A broken contract is rejected, so this test can fail.
    let bad = out.replacen("type:        \"int\"", "type:        \"integer\"", 1);
    assert_ne!(bad, out);
    assert!(cue_vet(&bad).unwrap().is_err());
}

