#[test]
fn declaration_errors() {
    #[derive(Debug, Deserialize, Docuconf)]
    #[allow(dead_code)]
    struct Bad {
        /// Lower-case names are not environment variable names.
        #[docuconf(env = "lower")]
        lower: String,
        /// Patterns must be RE2.
        #[docuconf(pattern = "(?=x)")]
        look: String,
        /// min does not apply to strings.
        #[docuconf(min = 1)]
        str_min: String,
        /// A file input under a reserved directory.
        #[docuconf(path = "/etc/ca.pem")]
        ca: docuconf::CaBundle,
        /// Watching is not implemented.
        #[docuconf(path = "/etc/app/notes/notes.txt", reload = "watch")]
        notes: docuconf::TextFile,
        /// The password of a keystore must be a secret.
        #[docuconf(path = "/etc/app/ks/ks.p12", password_var = "LOWER_NOT_SECRET")]
        ks: docuconf::Keystore,
        /// Not secret, so not a keystore password.
        lower_not_secret: String,
        /// Item bounds only apply to int lists.
        #[docuconf(item_min = 1)]
        names: Vec<String>,
        /// Item bounds must leave a range after narrowing to the item type.
        #[docuconf(item_min = 300)]
        ids: Vec<u8>,
    }
    // Mistakes visible in the attributes and the field type (a missing
    // description, a default that breaks its bounds or its type, a secret
    // or required variable with a default, a Duration without
    // humantime_serde) are compile errors; see src/compile_errors.rs.
    // These need the whole declaration.
    let err = docuconf::check_declaration::<Bad>().unwrap_err();
    let all = err.problems.join("\n");
    for want in [
        "lower (Bad.lower): variable name must match",
        "LOOK (Bad.look): pattern \"(?=x)\" is not valid RE2",
        "STR_MIN (Bad.str_min): attribute `min` does not apply to a string variable",
        "file input ca (Bad.ca): would be mounted at /etc",
        "file input notes (Bad.notes): reload = \"watch\" is not implemented",
        "file input ks (Bad.ks): password_var LOWER_NOT_SECRET must be a secret variable",
        "NAMES (Bad.names): attribute `item_min` does not apply to a list of strings variable",
        "IDS (Bad.ids): item_min 300 is above item_max 255",
    ] {
        assert!(all.contains(want), "missing {want:?} in\n{all}");
    }

    // Loading reports the declaration error, not violations.
    let e = docuconf::Loader::<Bad>::new()
        .env(Vec::<(String, String)>::new())
        .load()
        .unwrap_err();
    assert!(matches!(e, Error::Declaration(_)));
}

#[test]
fn list_item_bounds_are_exported_within_the_item_type() {
    #[derive(Debug, Deserialize, Docuconf)]
    #[allow(dead_code)]
    struct Lists {
        /// Narrow items get their type's range.
        a: Vec<u16>,
        /// Signed 32-bit items.
        b: Vec<i32>,
        /// User bounds inside the type's range.
        #[docuconf(item_min = -5, item_max = 100)]
        c: Vec<i8>,
        /// User bounds wider than the type are narrowed to it.
        #[docuconf(item_min = -1000, item_max = 1000)]
        d: Vec<u8>,
        /// 64-bit items have no implicit bounds.
        e: Vec<i64>,
    }
    let out = docuconf::export::<Lists>(&Meta::new("lists")).unwrap();
    let block = |name: &str| {
        let start = out.find(&format!("\t\t{name}: {{")).unwrap();
        let end = start + out[start..].find("\t\t}").unwrap();
        out[start..end].to_string()
    };
    assert!(
        block("A").contains("itemMin:     0\n") && block("A").contains("itemMax:     65535\n"),
        "{out}"
    );
    assert!(
        block("B").contains("itemMin:     -2147483648\n")
            && block("B").contains("itemMax:     2147483647\n"),
        "{out}"
    );
    assert!(
        block("C").contains("itemMin:     -5\n") && block("C").contains("itemMax:     100\n"),
        "{out}"
    );
    assert!(
        block("D").contains("itemMin:     0\n") && block("D").contains("itemMax:     255\n"),
        "{out}"
    );
    assert!(
        !block("E").contains("itemMin") && !block("E").contains("itemMax"),
        "{out}"
    );
    if let Some(res) = cue_vet(&out) {
        res.unwrap_or_else(|e| panic!("cue vet failed:\n{e}\n{out}"));
    }
}

#[test]
fn mount_collisions_and_path_env_rules() {
    #[derive(Debug, Deserialize, Docuconf)]
    #[allow(dead_code)]
    struct Bad {
        /// First file in a shared directory.
        #[docuconf(path = "/etc/app/shared/a.txt", path_env = "A_FILE")]
        a: docuconf::TextFile,
        /// Second file in a shared directory.
        #[docuconf(path = "/etc/app/shared/b.txt", path_env = "A_FILE")]
        b: docuconf::TextFile,
        /// A path that is not normalised.
        #[docuconf(path = "/etc/app/../x.txt")]
        c: docuconf::TextFile,
        /// Also the name of a variable.
        a_file: Option<String>,
    }
    let err = docuconf::check_declaration::<Bad>().unwrap_err();
    let all = err.problems.join("\n");
    for want in [
        "file input b (Bad.b): shares mount directory /etc/app/shared with file input a",
        "path_env A_FILE must not also be a declared variable",
        "path_env A_FILE is also used by file input a",
        "file input c (Bad.c): path \"/etc/app/../x.txt\" must be absolute and normalised",
    ] {
        assert!(all.contains(want), "missing {want:?} in\n{all}");
    }
}

